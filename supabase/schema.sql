      create policy "Guests can submit booking requests"
        on public.bookings for insert
        to anon, authenticated
        with check (
          length(trim(guest_name)) between 2 and 100
          and length(trim(guest_email)) between 3 and 254
          and position('@' in guest_email) > 1
          and length(trim(guest_phone)) between 7 and 30
