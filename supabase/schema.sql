create table if not exists public.blocked_dates (
  property_id text not null check (property_id in ('clandstein', 'coates')),
  blocked_on date not null,
  created_at timestamptz not null default now(),
  primary key (property_id, blocked_on)
);

create table if not exists public.availability_blocks (
  id bigint generated by default as identity primary key,
  property_id text not null check (property_id in ('clandstein', 'coates')),
  check_in date not null,
  check_out date not null,
  created_at timestamptz not null default now(),
  check (check_out >= check_in)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  property_id text not null check (property_id in ('clandstein', 'coates')),
  guest_name text not null,
  guest_email text not null,
  guest_phone text not null,
  guest_count integer not null check (guest_count between 1 and 11),
  check_in date not null,
  check_out date not null,
  status text not null default 'requested' check (status in ('requested', 'confirmed', 'cancelled')),
  created_at timestamptz not null default now(),
  check (check_out > check_in)
);

alter table public.bookings add column if not exists property text;
alter table public.bookings add column if not exists status text not null default 'requested';

create index if not exists bookings_availability_idx
  on public.bookings (property_id, check_in, check_out)
  where status in ('requested', 'confirmed');

