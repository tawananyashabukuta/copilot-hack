          and check_out > check_in
          and status = 'requested'
          and property_id in ('clandstein', 'coates')
        )
    $policy$;
  end if;
end;
$$;

create or replace function public.check_booking_availability(
  p_property_id text,
  p_check_in date,
  p_check_out date
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  has_conflict boolean;
begin
  if p_property_id is null or p_property_id not in ('clandstein', 'coates')
    or p_check_in is null or p_check_out is null or p_check_out < p_check_in then
    raise exception 'Please check your booking dates and try again.';
  end if;

  if exists (
    select 1 from public.availability_blocks as blocked
    where blocked.property_id = p_property_id
      and not (
        blocked.check_out < p_check_in
        or blocked.check_in > p_check_out
      )
  ) then
    return false;
  end if;

  if exists (
    select 1
    from pg_catalog.generate_series(p_check_in, p_check_out, interval '1 day') as requested(day)
    join public.blocked_dates as blocked on blocked.property_id = p_property_id
      and blocked.blocked_on = requested.day::date
  ) then
    return false;
  end if;

  if (
    select count(*) = 5 from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings'
      and column_name in ('name', 'property', 'email', 'phone', 'guests')
  ) then
    execute
      'select exists (
         select 1 from public.bookings as existing
         where existing.property = $1
           and coalesce(existing.status, ''requested'') <> ''cancelled''
           and not (
             existing.check_out < $2
             or existing.check_in > $3
           )
       )'
      into has_conflict
      using p_property_id, p_check_in, p_check_out;
  else
    execute
      'select exists (
         select 1 from public.bookings as existing
         where existing.property_id = $1
           and coalesce(existing.status, ''requested'') <> ''cancelled''
           and not (
             existing.check_out < $2
             or existing.check_in > $3
           )
       )'
      into has_conflict
      using p_property_id, p_check_in, p_check_out;
  end if;

  return not has_conflict;
end;
$$;

revoke all on function public.check_booking_availability(text, date, date) from public;
grant execute on function public.check_booking_availability(text, date, date) to anon, authenticated;

create or replace function public.create_booking(
  p_property_id text,
  p_guest_name text,
  p_guest_email text,
  p_guest_phone text,
  p_guest_count integer,
  p_check_in date,
  p_check_out date
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_booking_id uuid;
  night_count integer;
begin
  if p_property_id is null or p_property_id not in ('clandstein', 'coates')
    or p_guest_name is null or length(trim(p_guest_name)) not between 2 and 100
    or p_guest_email is null or length(trim(p_guest_email)) > 254 or position('@' in p_guest_email) < 2
    or p_guest_phone is null or length(trim(p_guest_phone)) not between 7 and 30
    or p_guest_count is null or p_guest_count < 1
    or p_check_in is null or p_check_out is null
    or p_check_in < current_date or p_check_out <= p_check_in then
    raise exception 'Please check your booking details and try again.';
  end if;

  if (p_property_id = 'clandstein' and p_guest_count > 6)
    or (p_property_id = 'coates' and p_guest_count > 11) then
    raise exception 'This stay cannot accommodate that many guests.';
  end if;

  night_count := p_check_out - p_check_in;
  if p_property_id = 'clandstein' and night_count < 3 then
    raise exception 'The houseboat has a minimum stay of 3 nights.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_property_id, 0));

  if not public.check_booking_availability(p_property_id, p_check_in, p_check_out) then
    raise exception 'Those dates are not available.';
  end if;

  if (
    select count(*) = 5 from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings'
      and column_name in ('name', 'property', 'email', 'phone', 'guests')
  ) then
    execute
      'insert into public.bookings (
         property, name, email, phone, guests, check_in, check_out
       ) values ($1, $2, $3, $4, $5, $6, $7)
       returning id'
      into new_booking_id
      using p_property_id, trim(p_guest_name), trim(p_guest_email), trim(p_guest_phone),
        p_guest_count, p_check_in, p_check_out;
  else
    insert into public.bookings (
      property_id, guest_name, guest_email, guest_phone, guest_count, check_in, check_out
    ) values (
      p_property_id, trim(p_guest_name), trim(p_guest_email), trim(p_guest_phone),
      p_guest_count, p_check_in, p_check_out
    ) returning id into new_booking_id;
  end if;

  return new_booking_id;
end;
$$;

